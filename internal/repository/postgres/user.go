package postgres

import (
	"context"
	"errors"
	"fmt"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/ashur/ttr/internal/domain"
)

// pgUniqueViolation is the SQLSTATE class for a unique constraint breach.
const pgUniqueViolation = "23505"

// userColumns is shared by every query so the scan order can never drift.
const userColumns = "id, email, full_name, created_at, updated_at"

// UserRepository stores users in PostgreSQL.
type UserRepository struct {
	pool *pgxpool.Pool
}

// NewUserRepository returns a repository backed by the given pool.
func NewUserRepository(pool *pgxpool.Pool) *UserRepository {
	return &UserRepository{pool: pool}
}

// Create inserts a user and returns the stored row, including the timestamps
// generated by the database. It returns domain.ErrAlreadyExists when the email
// is taken.
func (r *UserRepository) Create(ctx context.Context, in domain.CreateUserInput) (domain.User, error) {
	const query = `
		INSERT INTO users (email, full_name)
		VALUES ($1, $2)
		RETURNING ` + userColumns

	rows, err := r.pool.Query(ctx, query, in.Email, in.FullName)
	if err != nil {
		return domain.User{}, wrapUserErr("insert user", err)
	}
	user, err := pgx.CollectExactlyOneRow(rows, scanUser)
	if err != nil {
		return domain.User{}, wrapUserErr("insert user", err)
	}
	return user, nil
}

// GetByID returns one user. It returns domain.ErrNotFound when the id is
// unknown.
func (r *UserRepository) GetByID(ctx context.Context, id uuid.UUID) (domain.User, error) {
	const query = `SELECT ` + userColumns + ` FROM users WHERE id = $1`

	rows, err := r.pool.Query(ctx, query, id)
	if err != nil {
		return domain.User{}, wrapUserErr("select user", err)
	}
	user, err := pgx.CollectExactlyOneRow(rows, scanUser)
	if err != nil {
		return domain.User{}, wrapUserErr("select user", err)
	}
	return user, nil
}

// List returns up to limit users ordered newest first. When cursor is non-nil
// only rows strictly after it are returned.
//
// The WHERE clause compares the (created_at, id) tuple, which matches the
// descending composite index exactly: PostgreSQL seeks straight to the cursor
// instead of counting rows the way OFFSET would.
func (r *UserRepository) List(ctx context.Context, limit int32, cursor *domain.Cursor) ([]domain.User, error) {
	const query = `
		SELECT ` + userColumns + `
		FROM users
		WHERE $1::timestamptz IS NULL OR (created_at, id) < ($1::timestamptz, $2::uuid)
		ORDER BY created_at DESC, id DESC
		LIMIT $3`

	var (
		cursorCreatedAt any
		cursorID        any
	)
	if cursor != nil {
		cursorCreatedAt = cursor.CreatedAt
		cursorID = cursor.ID
	}

	rows, err := r.pool.Query(ctx, query, cursorCreatedAt, cursorID, limit)
	if err != nil {
		return nil, wrapUserErr("list users", err)
	}
	users, err := pgx.CollectRows(rows, scanUser)
	if err != nil {
		return nil, wrapUserErr("list users", err)
	}
	return users, nil
}

// Update applies a partial update. Nil fields are left untouched: they reach
// PostgreSQL as NULL and COALESCE keeps the stored value, which avoids
// assembling SQL from strings at runtime.
func (r *UserRepository) Update(ctx context.Context, in domain.UpdateUserInput) (domain.User, error) {
	const query = `
		UPDATE users
		SET email      = COALESCE($2, email),
		    full_name  = COALESCE($3, full_name),
		    updated_at = now()
		WHERE id = $1
		RETURNING ` + userColumns

	rows, err := r.pool.Query(ctx, query, in.ID, in.Email, in.FullName)
	if err != nil {
		return domain.User{}, wrapUserErr("update user", err)
	}
	user, err := pgx.CollectExactlyOneRow(rows, scanUser)
	if err != nil {
		return domain.User{}, wrapUserErr("update user", err)
	}
	return user, nil
}

// Delete removes a user. It returns domain.ErrNotFound when the id is unknown.
func (r *UserRepository) Delete(ctx context.Context, id uuid.UUID) error {
	const query = `DELETE FROM users WHERE id = $1`

	tag, err := r.pool.Exec(ctx, query, id)
	if err != nil {
		return wrapUserErr("delete user", err)
	}
	if tag.RowsAffected() == 0 {
		return domain.ErrNotFound
	}
	return nil
}

// Ping reports whether the database is reachable; used by the health service.
func (r *UserRepository) Ping(ctx context.Context) error {
	if err := r.pool.Ping(ctx); err != nil {
		return fmt.Errorf("ping postgres: %w", err)
	}
	return nil
}

// scanUser maps one row onto the domain model.
func scanUser(row pgx.CollectableRow) (domain.User, error) {
	var u domain.User
	err := row.Scan(&u.ID, &u.Email, &u.FullName, &u.CreatedAt, &u.UpdatedAt)
	return u, err
}

// wrapUserErr translates driver errors into domain sentinels so that layers
// above the repository never inspect SQLSTATE codes.
func wrapUserErr(op string, err error) error {
	if errors.Is(err, pgx.ErrNoRows) {
		return domain.ErrNotFound
	}

	var pgErr *pgconn.PgError
	if errors.As(err, &pgErr) && pgErr.Code == pgUniqueViolation {
		return fmt.Errorf("%s: %w", op, domain.ErrAlreadyExists)
	}
	return fmt.Errorf("%s: %w", op, err)
}
